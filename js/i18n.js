let currentLanguage = localStorage.getItem('dropmysong_language') || (navigator.language?.toLowerCase().startsWith('fr') ? 'fr' : 'en');
if (!translations[currentLanguage]) currentLanguage = 'en';

export function getLanguage() {
  return currentLanguage;
}

export function t(key, vars = {}) {
  let value = translations[currentLanguage]?.[key] ?? translations.en[key] ?? key;
  Object.entries(vars).forEach(([name, replacement]) => {
    value = value.replaceAll(`{${name}}`, String(replacement));
  });
  return value;
}

export function applyTranslations(root = document) {
  document.documentElement.lang = currentLanguage;
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-language]').forEach(button => {
    button.classList.toggle('active', button.dataset.language === currentLanguage);
  });
}

export function setLanguage(language) {
  if (!translations[language] || language === currentLanguage) return;
  currentLanguage = language;
  localStorage.setItem('dropmysong_language', currentLanguage);
  applyTranslations();
  window.dispatchEvent(new CustomEvent('dropmysong:languagechange', { detail: { language: currentLanguage } }));
}

export function initI18n() {
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.language));
  });
  applyTranslations();
}
