import React, { useMemo, useState } from 'react';
import GuestEventPreview from './GuestEventPreview.jsx';
import DjEventOverview from './DjEventOverview.jsx';

const modules = [
  { key: 'guest', icon: '♫', en: 'Song requests', fr: 'Demandes de chansons', enDesc: 'Request a song, follow its status and send a tip.', frDesc: 'Demandez une chanson, suivez son statut et laissez un pourboire.', path: '/index.html' },
  { key: 'dj', icon: '◉', en: 'DJ dashboard', fr: 'Tableau de bord DJ', enDesc: 'Manage the queue, events, tips and karaoke.', frDesc: 'Gérez la file, les événements, les pourboires et le karaoké.', path: '/dj.html' },
  { key: 'host', icon: '◇', en: 'Host portal', fr: 'Portail organisateur', enDesc: 'Manage event hosting and guest access.', frDesc: 'Gérez les événements et les accès invités.', path: '/host.html' },
  { key: 'karaoke', icon: '♪', en: 'Karaoke screen', fr: 'Écran karaoké', enDesc: 'Open the karaoke display for your event.', frDesc: 'Ouvrez l’écran karaoké de votre événement.', path: '/karaoke.html' },
];

const labels = {
  en: { tagline: 'Your music. Your event. Your moment.', description: 'Choose where you want to go. Your existing DJ and guest tools stay fully operational while we move to React.', open: 'Open', language: 'Language', event: 'Event', notice: 'React migration in progress: the existing pages remain active.', missing: 'For karaoke, open the event-specific link generated by your DJ dashboard.' },
  fr: { tagline: 'Votre musique. Votre événement. Votre moment.', description: 'Choisissez votre espace. Les outils DJ et invités restent opérationnels pendant la migration vers React.', open: 'Ouvrir', language: 'Langue', event: 'Événement', notice: 'Migration React en cours : les pages actuelles restent actives.', missing: 'Pour le karaoké, utilisez le lien de votre événement généré depuis le tableau de bord DJ.' },
};

export default function App() {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem('dropmysong_language') === 'fr' ? 'fr' : 'en'; }
    catch { return 'en'; }
  });
  const copy = labels[language];
  const event = useMemo(() => new URLSearchParams(window.location.search).get('event'), []);

  const changeLanguage = next => {
    setLanguage(next);
    try { localStorage.setItem('dropmysong_language', next); } catch { /* storage disabled */ }
    document.documentElement.lang = next;
  };

  const getLink = module => {
    const url = new URL(module.path, window.location.origin);
    // Preserve event links for guests. The karaoke page accepts an event ID,
    // so do not pass a guest event slug to it.
    if (module.key === 'guest' && event) url.searchParams.set('event', event);
    return url.pathname + url.search;
  };

  return (
    <div className="app-shell">
      <header className="app-header">
        <a href="/index.html" aria-label="DropMySong home"><img src="/assets/drop-my-song-logo.png" alt="DropMySong by DJ Maxo" /></a>
        <div className="language-select" aria-label={copy.language}>
          <button type="button" className={language === 'en' ? 'active' : ''} onClick={() => changeLanguage('en')} aria-pressed={language === 'en'}>EN</button>
          <button type="button" className={language === 'fr' ? 'active' : ''} onClick={() => changeLanguage('fr')} aria-pressed={language === 'fr'}>FR</button>
        </div>
      </header>
      <main>
        <p className="eyebrow">DJ MAXO PRESENTS</p>
        <h1>Drop<span>My</span>Song</h1>
        <p className="tagline">{copy.tagline}</p>
        <p className="intro">{copy.description}</p>
        {event && <GuestEventPreview slug={event} language={language} />}
        <DjEventOverview language={language} />
        <div className="module-grid">
          {modules.map(module => (
            <article className="module" key={module.key}>
              <div className="module-icon" aria-hidden="true">{module.icon}</div>
              <h2>{module[language === 'fr' ? 'fr' : 'en']}</h2>
              <p>{module[language === 'fr' ? 'frDesc' : 'enDesc']}</p>
              <a className="module-link" href={getLink(module)}>{copy.open} <span aria-hidden="true">→</span></a>
            </article>
          ))}
        </div>
        <p className="notice" role="status">{copy.notice}</p>
      </main>
    </div>
  );
}
